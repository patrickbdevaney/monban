"""Fixture release generator for ci/release/verify.py --self-test (P6-oracle-release-001, PLAN-6 D6, PREFLIGHT D-P2).

This file holds no key material and never writes keys under ci/release/fixtures/. Keys are created fresh per
self-test run in a caller-supplied temporary key directory (openssl PEM files) and in memory (TUF Ed25519 signers);
the caller deletes the directory when the run ends.

The generator follows the release layout contract in the verify.py docstring and runs the five D6 jobs in order
(build, sbom, attest, sign, tuf). A mutant name makes exactly one job misbehave, so the verifier must refuse the
result with that defect's own reason. It needs python-tuf, securesystemslib (with pyca/cryptography) and
OpenSSL >= 3.5 (ML-DSA, SLH-DSA).
"""

import base64
import hashlib
import json
import os
import subprocess
from datetime import datetime, timedelta, timezone

from securesystemslib.signer import CryptoSigner
from tuf.api.metadata import (
    Metadata,
    MetaFile,
    Role,
    Root,
    Snapshot,
    TargetFile,
    Targets,
    Timestamp,
)
from tuf.api.serialization.json import JSONSerializer

ALGS = ("ed25519", "slh-dsa-sha2-128s", "ml-dsa-87")
OSSL_ALG = {"ed25519": "ED25519", "slh-dsa-sha2-128s": "SLH-DSA-SHA2-128s", "ml-dsa-87": "ML-DSA-87"}
SUBJECT_PREFIX = b"aegis-release-v1 sha256:"
DSSE_TYPE = "application/vnd.in-toto+json"
ARTIFACT = "artifacts/monban-floor"

# Mutants generated by build_release(mut=...). The expected refusal reasons live in verify.py (SELF_TEST_CASES).
MUTANTS = (
    "root-2of5",  # root v1 carries only 2 of its 5 signatures (threshold 3)
    "root-rotation-2of5",  # 2.root.json signed by only 2 of the 5 keys trusted in root v1
    "root-policy-threshold2",  # root declares threshold 2 of 5 (fully signed): violates REL-2 policy
    "sig-bad-ed25519",  # one of the three artifact signatures is wrong
    "sig-bad-slh-dsa-sha2-128s",
    "sig-bad-ml-dsa-87",
    "sig-missing-ml-dsa-87",  # two signatures of three
    "sig-other-digest",  # ML-DSA signature valid, but over a different digest
    "sig-wrong-alg-key",  # the ml-dsa-87 slot holds an ML-DSA-44 key and signature
    "sums-mismatch",  # SHA256SUMS names a digest that is not the artifact's
    "no-marker-file",  # TEST_KEYS file absent, TUF test_keys markers kept
    "timestamp-expired",  # freeze: timestamp past its expiry
    "targets-expired",
    "sbom-mismatch",  # attestation names an SBOM digest that is not the shipped SBOM
    "subject-mismatch",  # attested subject digest != artifact sha256
    "attest-sig-bad",  # DSSE signature over the provenance does not verify
    "attest-key-reuse",  # provenance signed with the release Ed25519 key instead of a separate attest key
    "artifact-tampered",  # artifact changed after the tuf job signed targets
    "unlisted-file",  # file in the release that TUF does not list
    "private-key",  # a private key PEM shipped in the release
)


def _run(args, data=None):
    p = subprocess.run(args, input=data, capture_output=True, check=False)
    if p.returncode != 0:
        raise RuntimeError(f"{args[0]} {args[1]} failed: {p.stderr.decode(errors='replace').strip()}")
    return p.stdout


def _sha(b):
    return hashlib.sha256(b).hexdigest()


def _write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


class Keys:
    """Fresh throwaway keys for one self-test run (D-P2). PEM files go to keydir; TUF signers stay in memory."""

    def __init__(self, keydir, openssl):
        self.dir = keydir
        self.openssl = openssl
        os.makedirs(keydir, mode=0o700, exist_ok=True)
        self.root = [CryptoSigner.generate_ed25519() for _ in range(5)]
        self.targets = CryptoSigner.generate_ed25519()
        self.snapshot = CryptoSigner.generate_ed25519()
        self.timestamp = CryptoSigner.generate_ed25519()
        # Root metadata already published in this run, by (version, test_keys): an unrotated root is byte-identical
        # across releases, as in a real repository.
        self.roots = {}
        for name, alg in [(a, OSSL_ALG[a]) for a in ALGS] + [("attest", "ED25519"), ("ml-dsa-44", "ML-DSA-44")]:
            self._gen(name, alg)

    def _gen(self, name, alg):
        key = os.path.join(self.dir, name + ".key.pem")
        _run([self.openssl, "genpkey", "-algorithm", alg, "-out", key])
        os.chmod(key, 0o600)
        _run([self.openssl, "pkey", "-in", key, "-pubout", "-out", os.path.join(self.dir, name + ".pub.pem")])

    def key(self, name):
        return os.path.join(self.dir, name + ".key.pem")

    def pub(self, name):
        with open(os.path.join(self.dir, name + ".pub.pem"), "rb") as f:
            return f.read()

    def sign(self, name, msg):
        m = os.path.join(self.dir, "msg.bin")  # -rawin needs a sized file, not a pipe
        _write(m, msg)
        return _run([self.openssl, "pkeyutl", "-sign", "-rawin", "-inkey", self.key(name), "-in", m])


def subject_message(digest_hex):
    return SUBJECT_PREFIX + digest_hex.encode() + b"\n"


def dsse_pae(payload_type, payload):
    t = payload_type.encode()
    return b"DSSEv1 %d %s %d %s" % (len(t), t, len(payload), payload)


def build_release(out, keys, versions=None, mut=None, test_keys=True, now=None):
    """Write one release directory to `out` (which must not exist). versions: dict root/targets/snapshot/timestamp."""
    v = {"root": 1, "targets": 1, "snapshot": 1, "timestamp": 1}
    v.update(versions or {})
    now = now or datetime.now(timezone.utc).replace(microsecond=0)
    exp = now + timedelta(days=1)
    os.makedirs(out)

    # job 1: build (stand-in artifact bytes; the real pipeline writes the cargo auditable binary)
    art = b"Monban fixture artifact (not a binary)\n" + os.urandom(32)
    _write(os.path.join(out, ARTIFACT), art)
    art_sha = _sha(art)

    # job 2: sbom
    sbom = json.dumps(
        {
            "bomFormat": "CycloneDX",
            "specVersion": "1.6",
            "serialNumber": "urn:uuid:00000000-0000-4000-8000-%012x" % int.from_bytes(os.urandom(6), "big"),
            "version": 1,
            "metadata": {"component": {"type": "application", "name": "monban", "version": "0.0.0-fixture"}},
            "components": [],
        },
        indent=1,
        sort_keys=True,
    ).encode() + b"\n"
    _write(os.path.join(out, "sbom.cdx.json"), sbom)
    sbom_sha = _sha(sbom)

    sums_art = _sha(b"not the artifact") if mut == "sums-mismatch" else art_sha
    sums = f"{sums_art}  {ARTIFACT}\n{sbom_sha}  sbom.cdx.json\n".encode()
    _write(os.path.join(out, "SHA256SUMS"), sums)

    # job 3: attest (separate key; reads only the artifact digest and the SBOM)
    subj_sha = _sha(b"another build") if mut == "subject-mismatch" else art_sha
    by_sha = _sha(b"another sbom") if mut == "sbom-mismatch" else sbom_sha
    statement = {
        "_type": "https://in-toto.io/Statement/v1",
        "subject": [{"name": ARTIFACT, "digest": {"sha256": subj_sha}}],
        "predicateType": "https://slsa.dev/provenance/v1",
        "predicate": {
            "buildDefinition": {
                "buildType": "urn:aegis:release:d6:v1",
                "externalParameters": {"profile": "floor", "fixture": True},
                "internalParameters": {},
                "resolvedDependencies": [],
            },
            "runDetails": {
                "builder": {"id": "urn:aegis:ci:release-fixture"},
                "metadata": {"invocationId": "self-test", "startedOn": now.isoformat().replace("+00:00", "Z")},
                "byproducts": [{"name": "sbom.cdx.json", "digest": {"sha256": by_sha}}],
            },
        },
    }
    payload = json.dumps(statement, sort_keys=True, separators=(",", ":")).encode()
    attest_key = "ed25519" if mut == "attest-key-reuse" else "attest"
    dsig = keys.sign(attest_key, dsse_pae(DSSE_TYPE, payload))
    if mut == "attest-sig-bad":
        dsig = bytes([dsig[0] ^ 1]) + dsig[1:]
    env = {
        "payloadType": DSSE_TYPE,
        "payload": base64.b64encode(payload).decode(),
        "signatures": [{"keyid": "", "sig": base64.b64encode(dsig).decode()}],
    }
    _write(os.path.join(out, "provenance.intoto.json"), json.dumps(env, indent=1).encode() + b"\n")
    _write(os.path.join(out, "attest/attest.pub.pem"), keys.pub(attest_key))

    # job 4: sign (all three over the same digest of SHA256SUMS)
    msg = subject_message(_sha(sums))
    for alg in ALGS:
        if mut == "sig-missing-ml-dsa-87" and alg == "ml-dsa-87":
            continue
        m = subject_message(_sha(b"different digest")) if (mut == "sig-other-digest" and alg == "ml-dsa-87") else msg
        kname = "ml-dsa-44" if (mut == "sig-wrong-alg-key" and alg == "ml-dsa-87") else alg
        sig = keys.sign(kname, m)
        if mut == f"sig-bad-{alg}":
            sig = sig[:-1] + bytes([sig[-1] ^ 0x80]) if alg != "ed25519" else bytes([sig[0] ^ 1]) + sig[1:]
        _write(os.path.join(out, f"sigs/{alg}.subject"), m)
        _write(os.path.join(out, f"sigs/{alg}.sig"), sig)
        _write(os.path.join(out, f"sigs/{alg}.pub.pem"), keys.pub(kname))

    if test_keys and mut != "no-marker-file":
        _write(os.path.join(out, "TEST_KEYS"), b"test_keys: true\n")
    if mut == "private-key":
        with open(keys.key("ed25519"), "rb") as f:
            _write(os.path.join(out, "sigs/ed25519.key.pem"), f.read())

    # job 5: tuf
    extra = {"test_keys": True} if test_keys else None
    tdir = os.path.join(out, "tuf")
    os.makedirs(tdir)
    tfiles = {}
    for dp, _dn, fns in os.walk(out):
        for fn in fns:
            p = os.path.join(dp, fn)
            rel = os.path.relpath(p, out)
            if rel.split(os.sep)[0] == "tuf":
                continue
            tfiles[rel] = TargetFile.from_file(rel, p, ["sha256"])
    t_exp = now - timedelta(hours=1) if mut == "targets-expired" else exp
    ts_exp = now - timedelta(hours=1) if mut == "timestamp-expired" else exp
    targets = Metadata(Targets(version=v["targets"], expires=t_exp, targets=tfiles, unrecognized_fields=dict(extra or {})))
    snapshot = Metadata(Snapshot(version=v["snapshot"], expires=exp, meta={"targets.json": MetaFile(v["targets"])},
                                 unrecognized_fields=dict(extra or {})))
    timestamp = Metadata(Timestamp(version=v["timestamp"], expires=ts_exp, snapshot_meta=MetaFile(v["snapshot"]),
                                   unrecognized_fields=dict(extra or {})))
    targets.sign(keys.targets)
    snapshot.sign(keys.snapshot)
    timestamp.sign(keys.timestamp)
    ser = JSONSerializer(compact=False)
    for rv in range(1, v["root"] + 1):
        cache = None if mut in ("root-2of5", "root-rotation-2of5", "root-policy-threshold2") else (rv, test_keys)
        if cache in keys.roots:
            _write(os.path.join(tdir, f"{rv}.root.json"), keys.roots[cache])
            continue
        threshold = 2 if mut == "root-policy-threshold2" else 3
        root = Root(version=rv, expires=exp, consistent_snapshot=False, unrecognized_fields=dict(extra or {}))
        root.roles = {r: Role([], 1) for r in ("root", "targets", "snapshot", "timestamp")}
        for s in keys.root:
            root.add_key(s.public_key, "root")
        root.roles["root"].threshold = threshold
        root.add_key(keys.targets.public_key, "targets")
        root.add_key(keys.snapshot.public_key, "snapshot")
        root.add_key(keys.timestamp.public_key, "timestamp")
        md = Metadata(root)
        signers = keys.root
        if (mut == "root-2of5" and rv == 1) or (mut == "root-rotation-2of5" and rv == 2):
            signers = keys.root[:2]
        for s in signers:
            md.sign(s, append=True)
        data = md.to_bytes(ser)
        if cache is not None:
            keys.roots[cache] = data
        _write(os.path.join(tdir, f"{rv}.root.json"), data)
    targets.to_file(os.path.join(tdir, "targets.json"), ser)
    snapshot.to_file(os.path.join(tdir, "snapshot.json"), ser)
    timestamp.to_file(os.path.join(tdir, "timestamp.json"), ser)

    # after the tuf job: changes nobody signed
    if mut == "artifact-tampered":
        _write(os.path.join(out, ARTIFACT), art + b"\x00")
    if mut == "unlisted-file":
        _write(os.path.join(out, "artifacts/extra.bin"), b"unlisted\n")
    return out
