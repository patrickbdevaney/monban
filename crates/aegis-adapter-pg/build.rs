//! Compiles the PostgreSQL version gate from `supply-chain/engine-pins.toml` (P4-pg-001; R-DB-1, R-DB-8).
//!
//! The pins file is the single source of truth: every `kind = "postgres"` entry with `policy = "allow"` contributes
//! its `floor` (`major.minor`), and every `policy = "blocked"` entry contributes the major of its `version`. Nothing
//! is hand-copied into the adapter. The parser is deliberately tiny (no TOML crate, no build-dependency): it reads
//! `[section]` headers and single-line `key = "string"` pairs, which is the subset the pins file uses for these keys,
//! and it refuses the build (fail closed) on anything it cannot read exactly, mirroring the oracle's `Policy` checks:
//! a floor that is not `major.minor`, a blocked version without a leading major, an unknown policy, no allowed or no
//! blocked postgres pin, or a major that is both allowed and blocked.
//!
//! With feature `crdb` (P7-adapter-crdb-001, PREFLIGHT D-P7.8) it also compiles the CockroachDB floor from every
//! `kind = "crdb"` entry: `policy = "allow"` with a `floor` of exactly `major.minor.patch` (the release series is
//! `major.minor`, as in ci/engines.sh `floor_ok`); the entry's pinned `version` must be a release of the same series
//! at or above that floor; `policy = "blocked"` refuses the series of its `version`. No allowed crdb pin, a series
//! both allowed and blocked, or two floors for one series refuse the build. Without the feature, crdb entries are
//! skipped exactly as before and nothing crdb-specific is generated.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::PathBuf;

#[derive(Default)]
struct Entry {
    kind: Option<String>,
    policy: Option<String>,
    floor: Option<String>,
    version: Option<String>,
}

fn main() -> Result<(), String> {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").map_err(|e| format!("CARGO_MANIFEST_DIR: {e}"))?;
    let pins = PathBuf::from(&manifest).join("../../supply-chain/engine-pins.toml");
    println!("cargo:rerun-if-changed={}", pins.display());
    println!("cargo:rerun-if-changed=build.rs");
    let text = std::fs::read_to_string(&pins).map_err(|e| format!("{}: {e}", pins.display()))?;
    let entries = parse(&text)?;

    let mut floors: BTreeMap<u32, u32> = BTreeMap::new();
    let mut blocked: BTreeSet<u32> = BTreeSet::new();
    for (name, e) in &entries {
        if e.kind.as_deref() != Some("postgres") {
            continue;
        }
        match e.policy.as_deref() {
            Some("allow") => {
                let f = e.floor.as_deref().ok_or(format!("engines.{name}: policy allow without floor"))?;
                let (maj, mnr) = major_minor(f).ok_or(format!("engines.{name}.floor {f:?} is not major.minor"))?;
                let cur = floors.entry(maj).or_insert(mnr);
                *cur = (*cur).max(mnr); // same major twice: the higher floor applies (EnginePin::admit)
            }
            Some("blocked") => {
                let v = e.version.as_deref().ok_or(format!("engines.{name}: policy blocked without version"))?;
                let digits: String = v.chars().take_while(char::is_ascii_digit).collect();
                let maj = digits.parse::<u32>().map_err(|_| format!("engines.{name}.version {v:?} has no major"))?;
                blocked.insert(maj);
            }
            other => return Err(format!("engines.{name}.policy {other:?} (expected \"allow\" or \"blocked\")")),
        }
    }
    if floors.is_empty() || blocked.is_empty() {
        return Err(format!("{}: expected at least one allowed and one blocked postgres pin", pins.display()));
    }
    if let Some(m) = blocked.iter().find(|m| floors.contains_key(m)) {
        return Err(format!("{}: major {m} is both allowed and blocked", pins.display()));
    }

    let mut out = String::from("// @generated by aegis-adapter-pg/build.rs from supply-chain/engine-pins.toml.\n");
    out.push_str("/// `(major, minor)` floor per allowed PostgreSQL major (`policy = \"allow\"` pins).\n");
    out.push_str("pub const PG_FLOORS: &[(u32, u32)] = &[");
    for (maj, mnr) in &floors {
        let _ = write!(out, "({maj}, {mnr}), ");
    }
    out.push_str("];\n/// PostgreSQL majors refused whatever their minor (`policy = \"blocked\"` pins).\n");
    out.push_str("pub const PG_BLOCKED_MAJORS: &[u32] = &[");
    for maj in &blocked {
        let _ = write!(out, "{maj}, ");
    }
    out.push_str("];\n");
    let dst = PathBuf::from(std::env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?).join("pg_pins.rs");
    std::fs::write(&dst, out).map_err(|e| format!("{}: {e}", dst.display()))?;

    if std::env::var_os("CARGO_FEATURE_CRDB").is_some() {
        crdb(&entries, &pins)?;
    }
    Ok(())
}

/// `major.minor.patch`, each ASCII decimal within u32 (no `v`, no pre-release suffix).
fn release3(s: &str) -> Option<(u32, u32, u32)> {
    let num =
        |p: Option<&str>| p.filter(|p| !p.is_empty() && p.bytes().all(|c| c.is_ascii_digit()))?.parse::<u32>().ok();
    let mut it = s.split('.');
    let v = (num(it.next())?, num(it.next())?, num(it.next())?);
    if it.next().is_some() { None } else { Some(v) }
}

/// The CockroachDB floor table (`OUT_DIR/crdb_pins.rs`), feature `crdb` only.
fn crdb(entries: &BTreeMap<String, Entry>, pins: &std::path::Path) -> Result<(), String> {
    let mut floors: BTreeMap<(u32, u32), u32> = BTreeMap::new();
    let mut blocked: BTreeSet<(u32, u32)> = BTreeSet::new();
    for (name, e) in entries {
        if e.kind.as_deref() != Some("crdb") {
            continue;
        }
        match e.policy.as_deref() {
            Some("allow") => {
                let f = e.floor.as_deref().ok_or(format!("engines.{name}: crdb policy allow without floor"))?;
                let (maj, mnr, pat) =
                    release3(f).ok_or(format!("engines.{name}.floor {f:?} is not major.minor.patch"))?;
                let v = e.version.as_deref().ok_or(format!("engines.{name}: crdb pin without version"))?;
                let pv = release3(v).ok_or(format!("engines.{name}.version {v:?} is not major.minor.patch"))?;
                if (pv.0, pv.1) != (maj, mnr) || pv.2 < pat {
                    return Err(format!(
                        "engines.{name}: pinned version {v} is not in floor series {maj}.{mnr} at or above {f}"
                    ));
                }
                if floors.insert((maj, mnr), pat).is_some() {
                    return Err(format!("engines.{name}: a second crdb floor for series {maj}.{mnr}"));
                }
            }
            Some("blocked") => {
                let v = e.version.as_deref().ok_or(format!("engines.{name}: crdb policy blocked without version"))?;
                let mut parts = v.split('.');
                let series = match (parts.next(), parts.next()) {
                    (Some(a), Some(b)) => {
                        let b: String = b.chars().take_while(char::is_ascii_digit).collect();
                        major_minor(&format!("{a}.{b}"))
                    }
                    _ => None,
                };
                blocked.insert(series.ok_or(format!("engines.{name}.version {v:?} has no major.minor"))?);
            }
            other => return Err(format!("engines.{name}.policy {other:?} (expected \"allow\" or \"blocked\")")),
        }
    }
    if floors.is_empty() {
        return Err(format!("{}: feature crdb needs at least one allowed kind = \"crdb\" pin", pins.display()));
    }
    if let Some((a, b)) = blocked.iter().find(|s| floors.contains_key(s)) {
        return Err(format!("{}: crdb series {a}.{b} is both allowed and blocked", pins.display()));
    }
    let mut out = String::from("// @generated by aegis-adapter-pg/build.rs from supply-chain/engine-pins.toml.\n");
    out.push_str(
        "/// `(major, minor, patch)` floor per allowed CockroachDB release series (`kind = \"crdb\"` pins).\n",
    );
    out.push_str("pub const CRDB_FLOORS: &[(u32, u32, u32)] = &[");
    for ((maj, mnr), pat) in &floors {
        let _ = write!(out, "({maj}, {mnr}, {pat}), ");
    }
    out.push_str("];\n/// CockroachDB release series refused whatever their patch (`policy = \"blocked\"` pins).\n");
    out.push_str("pub const CRDB_BLOCKED_SERIES: &[(u32, u32)] = &[");
    for (maj, mnr) in &blocked {
        let _ = write!(out, "({maj}, {mnr}), ");
    }
    out.push_str("];\n");
    let dst = PathBuf::from(std::env::var("OUT_DIR").map_err(|e| format!("OUT_DIR: {e}"))?).join("crdb_pins.rs");
    std::fs::write(&dst, out).map_err(|e| format!("{}: {e}", dst.display()))
}

/// `[engines.NAME]` sections with their single-line string keys. Other sections and keys are ignored; array
/// continuation lines start with `"` and never look like `key = ...`.
fn parse(text: &str) -> Result<BTreeMap<String, Entry>, String> {
    let mut out: BTreeMap<String, Entry> = BTreeMap::new();
    let mut cur: Option<String> = None;
    for (no, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if let Some(rest) = line.strip_prefix('[') {
            if rest.starts_with('[') {
                return Err(format!("engine-pins.toml:{}: arrays of tables are not expected", no + 1));
            }
            let head = rest.split(']').next().unwrap_or("").trim();
            cur = head.strip_prefix("engines.").map(str::to_owned);
            if let Some(name) = &cur
                && out.insert(name.clone(), Entry::default()).is_some()
            {
                return Err(format!("engine-pins.toml:{}: duplicate section engines.{name}", no + 1));
            }
            continue;
        }
        let Some(name) = &cur else { continue };
        let Some((k, v)) = line.split_once('=') else { continue };
        let k = k.trim();
        if !k.bytes().all(|b| b.is_ascii_lowercase() || b == b'_') {
            continue;
        }
        let slot = match out.get_mut(name) {
            Some(e) => match k {
                "kind" => &mut e.kind,
                "policy" => &mut e.policy,
                "floor" => &mut e.floor,
                "version" => &mut e.version,
                _ => continue,
            },
            None => continue,
        };
        let s = string_value(v.trim()).ok_or(format!("engine-pins.toml:{}: {k} is not a plain string", no + 1))?;
        if slot.replace(s).is_some() {
            return Err(format!("engine-pins.toml:{}: duplicate key {k} in engines.{name}", no + 1));
        }
    }
    Ok(out)
}

/// `"text"` optionally followed by a `#` comment; no escapes (refused if present).
fn string_value(v: &str) -> Option<String> {
    let rest = v.strip_prefix('"')?;
    let (body, tail) = rest.split_once('"')?;
    let tail = tail.trim();
    if body.contains('\\') || !(tail.is_empty() || tail.starts_with('#')) {
        return None;
    }
    Some(body.to_owned())
}

fn major_minor(s: &str) -> Option<(u32, u32)> {
    let (a, b) = s.split_once('.')?;
    let num =
        |p: &str| if !p.is_empty() && p.bytes().all(|c| c.is_ascii_digit()) { p.parse::<u32>().ok() } else { None };
    Some((num(a)?, num(b)?))
}
