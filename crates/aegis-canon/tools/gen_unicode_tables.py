"""Generate crates/aegis-canon/src/unicode_tables.rs from Python's unicodedata (stdlib only; run with python3 -I).

The tables pin the Unicode version that the canon-diff reference (oracles/canon-diff/canon_ref.py) uses, so the Rust
NFC check and the A-label validity filter agree with it byte for byte. Re-run and commit the output whenever the
reference's Python (and therefore its Unicode version) changes:

    python3 -I crates/aegis-canon/tools/gen_unicode_tables.py > crates/aegis-canon/src/unicode_tables.rs
"""
import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def canon_decomp(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def main():
    w = sys.stdout.write
    w("// @generated by crates/aegis-canon/tools/gen_unicode_tables.py from Python unicodedata %s. Do not edit.\n"
      % unicodedata.unidata_version)
    w("//! Unicode %s data: canonical combining classes, canonical decompositions, primary composites, the\n"
      % unicodedata.unidata_version)
    w("//! general-category L/M/N set and the set of code points that ASCII-or-Unicode lowercasing changes.\n\n")
    w("pub const UNICODE_VERSION: &str = \"%s\";\n\n" % unicodedata.unidata_version)

    ccc = []
    cur = None
    for cp in range(MAX):
        c = 0 if is_surrogate(cp) else unicodedata.combining(chr(cp))
        if c and cur and cur[1] == cp - 1 and cur[2] == c:
            cur[1] = cp
        elif c:
            cur = [cp, cp, c]
            ccc.append(cur)
        else:
            cur = None
    w("/// (first, last, canonical combining class), sorted, non-zero classes only.\n")
    w("pub(crate) static CCC: &[(u32, u32, u8)] = &[\n")
    for a, b, c in ccc:
        w("    (0x%X, 0x%X, %d),\n" % (a, b, c))
    w("];\n\n")

    dec, comp = [], []
    for cp in range(MAX):
        if is_surrogate(cp) or 0xAC00 <= cp <= 0xD7A3:
            continue
        d = canon_decomp(cp)
        if d is None:
            continue
        if len(d) == 1:
            dec.append((cp, d[0], 0))
        elif len(d) == 2:
            dec.append((cp, d[0], d[1]))
            if unicodedata.normalize("NFC", chr(cp)) == chr(cp):
                comp.append((d[0], d[1], cp))
        else:
            raise SystemExit("unexpected canonical decomposition length for U+%04X" % cp)
    comp.sort()
    w("/// (code point, first, second-or-0): one level of canonical decomposition (applied recursively). Hangul\n")
    w("/// syllables are algorithmic and not listed.\n")
    w("pub(crate) static DECOMP: &[(u32, u32, u32)] = &[\n")
    for a, b, c in dec:
        w("    (0x%X, 0x%X, 0x%X),\n" % (a, b, c))
    w("];\n\n")
    w("/// (first, second, primary composite), sorted by (first, second). Composition exclusions are absent.\n")
    w("pub(crate) static COMPOSE: &[(u32, u32, u32)] = &[\n")
    for a, b, c in comp:
        w("    (0x%X, 0x%X, 0x%X),\n" % (a, b, c))
    w("];\n\n")

    lmn = ranges(lambda cp: not is_surrogate(cp) and unicodedata.category(chr(cp))[0] in "LMN")
    w("/// Code point ranges whose general category is L*, M* or N*.\n")
    w("pub(crate) static LMN: &[(u32, u32)] = &[\n")
    for a, b in lmn:
        w("    (0x%X, 0x%X),\n" % (a, b))
    w("];\n\n")

    low = ranges(lambda cp: not is_surrogate(cp) and chr(cp).lower() != chr(cp))
    w("/// Code point ranges that full lowercasing changes (str.lower() != itself).\n")
    w("pub(crate) static LOWER_CHANGES: &[(u32, u32)] = &[\n")
    for a, b in low:
        w("    (0x%X, 0x%X),\n" % (a, b))
    w("];\n")


if __name__ == "__main__":
    main()
